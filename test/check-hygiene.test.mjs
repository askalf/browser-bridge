// scripts/check-hygiene.mjs: the em dash and model-attribution checks that
// run in CI and from `npm run hygiene`. Em dashes are written as \u2014 so this
// file passes its own check.
import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { findEmDashes, findAttribution, findBodyProblems } from '../scripts/check-hygiene.mjs';

const D = '\u2014';
const script = fileURLToPath(new URL('../scripts/check-hygiene.mjs', import.meta.url));

test('findEmDashes reports added lines only, with file and new line number', () => {
  const diff = [
    'diff --git a/CHANGELOG.md b/CHANGELOG.md',
    '--- a/CHANGELOG.md',
    '+++ b/CHANGELOG.md',
    '@@ -3,0 +4,2 @@',
    `+### Added ${D} tools`,
    '+plain line',
    '@@ -10 +12 @@',
    '-old line',
    `+new ${D} line`,
  ].join('\n');
  assert.deepEqual(findEmDashes(diff), [
    { file: 'CHANGELOG.md', line: 4, text: `### Added ${D} tools` },
    { file: 'CHANGELOG.md', line: 12, text: `new ${D} line` },
  ]);
});

test('findEmDashes passes a reworded line that already had an em dash', () => {
  const diff = [
    '+++ b/README.md', '@@ -5 +5 @@', `-old wording ${D} kept`, `+new wording ${D} kept`,
    '@@ -9 +9 @@', `-one ${D} here`, `+one ${D} here ${D} and a new one`,
  ].join('\n');
  assert.deepEqual(findEmDashes(diff), [
    { file: 'README.md', line: 9, text: `one ${D} here ${D} and a new one` },
  ]);
});

test('findEmDashes counts context lines toward the new-file line number', () => {
  const diff = [
    'diff --git a/a.md b/a.md', '--- a/a.md', '+++ b/a.md', '@@ -10,2 +10,3 @@',
    ' context', `+text ${D} value`, ' more context',
  ].join('\n');
  assert.deepEqual(findEmDashes(diff), [{ file: 'a.md', line: 11, text: `text ${D} value` }]);
});

test('findEmDashes reads --- and +++ inside a hunk as content, not headers', () => {
  // A removed SQL comment `-- old` arrives as `--- old`; an added `++ x` as `+++ x`.
  const diff = [
    'diff --git a/q.sql b/q.sql', '--- a/q.sql', '+++ b/q.sql', '@@ -1,2 +1,2 @@',
    `--- old ${D} note`, `+-- new ${D} note`, '-x', '+++ still q.sql',
  ].join('\n');
  assert.deepEqual(findEmDashes(diff), []);
  const added = diff + `\n@@ -9,0 +9 @@\n+new ${D} here`;
  assert.deepEqual(findEmDashes(added), [{ file: 'q.sql', line: 9, text: `new ${D} here` }]);
});

test('findEmDashes skips lockfiles and deleted files, and passes an en dash or hyphen', () => {
  const diff = [
    'diff --git a/package-lock.json b/package-lock.json',
    '--- a/package-lock.json', '+++ b/package-lock.json', '@@ -1 +1 @@', `+"x ${D} y"`,
    'diff --git a/gone.md b/gone.md', '--- a/gone.md', '+++ /dev/null', '@@ -1 +0,0 @@', `-old ${D}`,
    'diff --git a/docs/a.md b/docs/a.md',
    '--- a/docs/a.md', '+++ b/docs/a.md', '@@ -0,0 +1,2 @@', '+range 1\u20132', '+a - b',
  ].join('\n');
  assert.deepEqual(findEmDashes(diff), []);
});

