// Runs the CLI in a throwaway repo, so each mode is checked end to end and
// each failure is pinned to the check that fired.
function withRepo(fn) {
  const dir = mkdtempSync(join(tmpdir(), 'hygiene-'));
  const owner = { GIT_AUTHOR_NAME: 'askalf', GIT_AUTHOR_EMAIL: 'o@users.noreply.github.com', GIT_COMMITTER_NAME: 'askalf', GIT_COMMITTER_EMAIL: 'o@users.noreply.github.com' };
  const model = { GIT_AUTHOR_NAME: 'Claude', GIT_AUTHOR_EMAIL: 'noreply@anthropic.com' };
  const git = (args, env = {}) => execFileSync('git', args, { cwd: dir, encoding: 'utf8', env: { ...process.env, ...owner, ...env } });
  const cli = (args, env = {}) => {
    try {
      execFileSync(process.execPath, [script, ...args], { cwd: dir, stdio: 'pipe', env: { ...process.env, ...owner, ...env } });
      return { status: 0, err: '' };
    } catch (e) { return { status: e.status, err: String(e.stderr) }; }
  };
  const write = (text) => writeFileSync(join(dir, 'a.md'), text);
  try {
    git(['init', '-q', '-b', 'main']);
    write('base\n');
    git(['add', '.']); git(['commit', '-qm', 'base']);
    fn({ dir, git, cli, write, model });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test('--range passes a clean commit and pins each failure to its check', () => {
  withRepo(({ git, cli, write, model }) => {
    write('base\nclean\n'); git(['commit', '-qam', 'clean']);
    assert.equal(cli(['--range', 'HEAD~1..HEAD']).status, 0);

    write('base\nclean\nby a model\n'); git(['commit', '-qam', 'model'], model);
    let r = cli(['--range', 'HEAD~1..HEAD']);
    assert.equal(r.status, 1);
    assert.match(r.err, /author is Claude <noreply@anthropic\.com>/);
    assert.doesNotMatch(r.err, /em dash/);

    write(`base\nclean\nby a model\nbad ${D} line\n`); git(['commit', '-qam', 'dash']);
    r = cli(['--range', 'HEAD~1..HEAD']);
    assert.equal(r.status, 1);
    assert.match(r.err, /a\.md:4: em dash in added text/);
    assert.doesNotMatch(r.err, /author is/);
  });
});

test('--staged checks only what is staged', () => {
  withRepo(({ git, cli, write }) => {
    write(`base\nnew ${D} line\n`);
    assert.equal(cli(['--staged']).status, 0, 'unstaged change is not checked');
    git(['add', 'a.md']);
    const r = cli(['--staged']);
    assert.equal(r.status, 1);
    assert.match(r.err, /a\.md:2: em dash/);
  });
});

test('--commit-msg checks the message and the identity git will commit as', () => {
  withRepo(({ dir, git, cli, model }) => {
    const msg = join(dir, 'MSG');
    // git sets GIT_EDITOR=: for the hook when no editor opens (-m, -F, --no-edit).
    const noEditor = { GIT_EDITOR: ':' };
    const editor = { GIT_EDITOR: 'vi' };
    writeFileSync(msg, 'fix: a thing\n\n# a comment line git strips\n');
    assert.equal(cli(['--commit-msg', msg], editor).status, 0);
    let r = cli(['--commit-msg', msg], { ...editor, ...model });
    assert.equal(r.status, 1);
    assert.match(r.err, /author is Claude/);
    writeFileSync(msg, 'fix\n\nCo-Authored-By: ChatGPT <noreply@openai.com>\n');
    r = cli(['--commit-msg', msg], noEditor);
    assert.equal(r.status, 1);
    assert.match(r.err, /Co-Authored-By: ChatGPT/);
    writeFileSync(msg, `fix ${D} thing\n`);
    assert.match(cli(['--commit-msg', msg], noEditor).err, /em dash/);

    // Without an editor git keeps # lines, so they are checked, a bare # included.
    writeFileSync(msg, `#113 fix ${D} thing\n`);
    assert.match(cli(['--commit-msg', msg], noEditor).err, /em dash/);
    writeFileSync(msg, 'fix\n#\n# Co-Authored-By: ChatGPT <noreply@openai.com>\n');
    assert.match(cli(['--commit-msg', msg], noEditor).err, /Co-Authored-By: ChatGPT/);

    // With an editor git strips # lines, so its template is not checked, in any locale.
    const template = (lines) => ['fix: clean message', '', ...lines, ''].join('\n');
    writeFileSync(msg, template([
      '# Please enter the commit message for your changes. Lines starting',
      "# with '#' will be ignored, and an empty message aborts the commit.",
      '#', '# On branch gpt-5-migration', '#\tnew file:   gemini-2.5-pro.json', '#',
    ]));
    assert.equal(cli(['--commit-msg', msg], editor).status, 0);
    writeFileSync(msg, template([
      '# Bitte geben Sie eine Commit-Beschreibung f\u00fcr Ihre \u00c4nderungen ein.',
      '#', '# Auf Branch gpt-5-migration', '#\tneue Datei:   gemini-2.5-pro.json', '#',
    ]));
    assert.equal(cli(['--commit-msg', msg], editor).status, 0);

    // Under a non-strip cleanup mode git keeps # lines even with an editor.
    writeFileSync(msg, `fix\n# kept ${D} line\n`);
    git(['config', 'commit.cleanup', 'verbatim']);
    assert.match(cli(['--commit-msg', msg], editor).err, /em dash/);
    git(['config', 'commit.cleanup', 'strip']);
    assert.equal(cli(['--commit-msg', msg], noEditor).status, 0, 'cleanup=strip drops # lines without an editor too');
    git(['config', '--unset', 'commit.cleanup']);
    assert.equal(cli(['--commit-msg', msg], editor).status, 0);

    // core.commentChar decides which lines are comments.
    git(['config', 'core.commentChar', ';']);
    writeFileSync(msg, template([';', '; On branch gpt-5-migration', ';']));
    assert.equal(cli(['--commit-msg', msg], editor).status, 0);
    writeFileSync(msg, `#113 fix ${D} thing\n`);
    assert.match(cli(['--commit-msg', msg], editor).err, /em dash/, '# is not a comment then');
    git(['config', '--unset', 'core.commentChar']);

    // commit -v: everything from the scissors line on is the diff, not the message.
    writeFileSync(msg, [
      'fix: clean message', '',
      '# ------------------------ >8 ------------------------',
      '# Do not modify or remove the line above.',
      'diff --git a/a.md b/a.md', ` a ${D} b`, '+tested on claude-sonnet-5', '',
    ].join('\n'));
    assert.equal(cli(['--commit-msg', msg], editor).status, 0);
    assert.equal(cli(['--commit-msg', msg], noEditor).status, 0);
  });
});

test('findBodyProblems flags a generator footer, a session link and an em dash', () => {
  const body = `## Summary\n\nA ${D} B\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_x)_`;
  assert.deepEqual(findBodyProblems(body), [
    'message contains "claude.ai/code/session_x"',
    'message contains "Generated by [Claude Code"',
    'contains an em dash',
  ]);
  assert.deepEqual(findBodyProblems('## Summary\n\nWorks with Claude Desktop.'), []);
  // Describing the check is not a session link.
  assert.deepEqual(findBodyProblems('- `--pr-body` flags a claude.ai/code session link'), []);
});
